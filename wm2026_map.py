# Projektion
LNG_MIN, LNG_MAX = -130.0, -60.0
LAT_MIN, LAT_MAX = 14.0, 55.0
W, H = 1000, 640

def project(lng, lat):
    x = (lng - LNG_MIN) / (LNG_MAX - LNG_MIN) * W
    y = (LAT_MAX - lat) / (LAT_MAX - LAT_MIN) * H
    return round(x, 1), round(y, 1)

def poly_points(coords):
    return " ".join(f"{x},{y}" for x, y in (project(lng, lat) for lng, lat in coords))

